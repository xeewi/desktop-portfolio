import { describe, expect, it } from 'vitest'
import css from '../../icons/icons.css?raw'
import { OSES } from '../../themes'
import { ICON_NAMES } from './Icon'

// every icon file shipped, as './<chrome>/<name>.<ext>' (the paths icons.css uses)
const files = Object.keys(import.meta.glob('../../icons/*/*', { query: '?url' })).map((f) => f.replace('../../icons/', './'))

/** { selector: { '--icon-user': './vista/user.png', … } } from the generated icons.css */
const blocks = Object.fromEntries(
  [...css.matchAll(/(\[data-chrome[^\]]*\])\s*\{([^}]*)\}/g)].map(([, selector, body]) => [
    selector,
    Object.fromEntries([...body.matchAll(/(--icon-[\w-]+):\s*url\('([^']+)'\)/g)].map(([, k, v]) => [k, v])),
  ]),
)

describe('OS icons (icons/icons.css, generated by scripts/fetch-icons.mjs)', () => {
  it('has a default set, used by any chrome without its own', () => {
    expect(Object.keys(blocks['[data-chrome]'] ?? {})).toEqual(ICON_NAMES.map((n) => `--icon-${n}`))
  })

  for (const os of OSES) {
    it(`gives ${os.name} every icon, each pointing to a real file`, () => {
      const own = blocks[`[data-chrome='${os.chrome}']`] ?? {}
      const set = { ...blocks['[data-chrome]'], ...own }
      for (const name of ICON_NAMES) expect(files).toContain(set[`--icon-${name}`])
    })
  }

  it('gives each OS its own icons (only the default chrome may fall back)', () => {
    const chromes = new Set(OSES.map((o) => o.chrome))
    const own = [...chromes].filter((c) => blocks[`[data-chrome='${c}']`])
    expect(own.length).toBeGreaterThanOrEqual(chromes.size - 1)
  })
})
